-- ACL medida em produção, idêntica nas 15 tabelas:
--   postgres=arwdDxtm / anon=arwdDxtm / authenticated=arwdDxtm / service_role=arwdDxtm
--
-- Leitura importante: `anon` e `authenticated` POSSUEM privilégio de tabela
-- para INSERT/UPDATE/DELETE. Quem barra a escrita é o RLS (não há policy de
-- escrita para `anon`). Ou seja: em 14 tabelas, o `authenticated` tem
-- privilégio E policy liberada — é exatamente a dívida do Bloco 3.
--
-- Descomente apenas se estiver reconstruindo as permissões padrao do Supabase:
--
-- grant all on table public.acesso_rapido   to anon, authenticated, service_role;
-- grant all on table public.admin_settings  to anon, authenticated, service_role;
