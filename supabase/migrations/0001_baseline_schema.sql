-- 3. CONSTRAINTS
-- ----------------------------------------------------------------------------
-- Por tabela: PRIMARY KEY (id) + CHECK de `publish_status`.
-- `admin_settings` troca o CHECK por UNIQUE (scope).
--
-- As chaves são `generated by default as identity`, que criam as sequences
-- implicitamente — NÃO criar sequences manualmente.
--
-- Índices: os 16 índices existentes são TODOS derivados das constraints abaixo
-- (*_pkey e admin_settings_scope_key), criados automaticamente pelo Postgres.
-- Por isso não há seção de CREATE INDEX neste arquivo.

alter table only public.acesso_rapido add constraint acesso_rapido_publish_status_check CHECK ((publish_status = ANY (ARRAY['published'::text, 'draft'::text])));
alter table only public.acesso_rapido add constraint acesso_rapido_pkey PRIMARY KEY (id);

alter table only public.admin_settings add constraint admin_settings_pkey PRIMARY KEY (id);
alter table only public.admin_settings add constraint admin_settings_scope_key UNIQUE (scope);

alter table only public.agenda_eventos add constraint agenda_eventos_publish_status_check CHECK ((publish_status = ANY (ARRAY['published'::text, 'draft'::text])));
alter table only public.agenda_eventos add constraint agenda_eventos_pkey PRIMARY KEY (id);

