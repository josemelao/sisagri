-- ----------------------------------------------------------------------------
-- 1. EXTENSÕES
-- ----------------------------------------------------------------------------
-- Instaladas hoje (pg_extension): pg_stat_statements 1.11, pgcrypto 1.3,
-- uuid-ossp 1.1 (todas no schema `extensions`), supabase_vault 0.3.1 (`vault`)
-- e plpgsql 1.0 (`pg_catalog`, nativa).
--
-- Em projeto novo criado pelo Supabase, `pgcrypto` e `uuid-ossp` normalmente já
-- vêm instaladas no schema `extensions`. As linhas abaixo são a rede de
-- segurança para reconstruir o ambiente fora do Supabase.
create extension if not exists pgcrypto with schema extensions;
create extension if not exists "uuid-ossp" with schema extensions;


