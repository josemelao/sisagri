-- ============================================================================
-- 0016_audit_log.sql — Fase 2.2: historico de alteracoes
-- ----------------------------------------------------------------------------
-- Registra QUEM alterou, O QUE foi alterado e QUAIS campos mudaram nas 14
-- tabelas de conteudo. Nunca grava valores: o log nao pode virar vazamento de
-- CPF, telefone, chassi ou RENAVAM.
--
-- Decisoes (aprovadas pelo dono em 2026-10-28):
--   - falha da auditoria NAO derruba a gravacao (exception -> raise warning);
--   - importacao em massa (RPC replace_collection) gera uma linha por item,
--     sem alterar a 0013;
--   - retencao de 12 meses por funcao manual `limpar_audit_log(meses)`.
--
-- Ordem de deploy: aplicar em `supabase-teste` primeiro. Producao somente com
-- autorizacao explicita.
--
-- Idempotente: `create table if not exists`, `drop trigger if exists`,
-- `create or replace function`, `drop policy if exists`.
--
-- Rollback:
--   do $$
--   declare t text;
--   begin
--     foreach t in array array['acesso_rapido','agenda_eventos','arquivos',
--       'avisos','escala_ferias','funcionarios','info_juridico','info_municipio',
--       'info_orgaos','manuais','processos','servicos','sistemas','veiculos'] loop
--       execute format('drop trigger if exists auditar_alteracoes on public.%I', t);
--     end loop;
--   end $$;
--   drop function if exists public.limpar_audit_log(integer);
--   drop function if exists public.registrar_auditoria();
--   drop table if exists public.audit_log;
-- ============================================================================

create table if not exists public.audit_log (
  id bigint generated by default as identity not null,
  tabela text not null,
  registro_id bigint,
  operacao text not null,
  campos text[] not null default '{}',
  rotulo text,
  usuario_id uuid,
  usuario_email text,
  em timestamptz not null default now(),
  constraint audit_log_pkey primary key (id),
  constraint audit_log_operacao_check check (operacao in ('insert', 'update', 'delete'))
);

comment on table public.audit_log is
  'Historico de alteracoes do painel (fase 2.2). Guarda nomes de campos e um rotulo, nunca valores.';
comment on column public.audit_log.campos is
  'Campos alterados. Apenas nomes de coluna: o conteudo nunca e copiado para ca.';

create index if not exists audit_log_em_idx
  on public.audit_log (em desc);
create index if not exists audit_log_tabela_em_idx
  on public.audit_log (tabela, em desc);
create index if not exists audit_log_usuario_em_idx
  on public.audit_log (usuario_email, em desc);

-- ----------------------------------------------------------------------------
-- Acesso: anon nunca le; authenticated le so se for editor (admin/servidor).
-- O INSERT e feito pelo trigger (SECURITY DEFINER), nunca pelo cliente.
-- ----------------------------------------------------------------------------
alter table public.audit_log enable row level security;

revoke all on public.audit_log from anon, authenticated;
grant select on public.audit_log to authenticated;

drop policy if exists "Historico somente para editores" on public.audit_log;
create policy "Historico somente para editores" on public.audit_log
  for select to authenticated
  using (public.pode_editar());

do $$
declare
  sequencia text;
begin
  sequencia := pg_get_serial_sequence('public.audit_log', 'id');
  if sequencia is not null then
    execute format('revoke all on sequence %s from anon, authenticated', sequencia);
  end if;
end $$;

-- ----------------------------------------------------------------------------
-- Trigger de auditoria
-- ----------------------------------------------------------------------------
create or replace function public.registrar_auditoria()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_antes    jsonb;
  v_depois   jsonb;
  v_campos   text[] := '{}';
  v_rotulo   text;
  v_operacao text := lower(tg_op);
begin
  if tg_op in ('UPDATE', 'DELETE') then
    v_antes := to_jsonb(old);
  end if;
  if tg_op in ('INSERT', 'UPDATE') then
    v_depois := to_jsonb(new);
  end if;

  -- Rotulo legivel do registro: titulo > nome > assunto. Sem valor de PII.
  v_rotulo := coalesce(
    v_depois ->> 'titulo', v_antes ->> 'titulo',
    v_depois ->> 'nome',   v_antes ->> 'nome',
    v_depois ->> 'assunto', v_antes ->> 'assunto'
  );

  if tg_op = 'INSERT' then
    -- Criacao: a operacao ja diz tudo e o rotulo identifica o registro. Listar
    -- todas as colunas (inclusive defaults e nulos) so faria ruido na tela.
    v_campos := '{}';
  elsif tg_op = 'UPDATE' then
    select coalesce(array_agg(chave order by chave), '{}')
      into v_campos
      from jsonb_object_keys(v_depois) as chave
     where chave not in ('id', 'updated_at')
       and (v_antes -> chave) is distinct from (v_depois -> chave);
  end if;

  insert into public.audit_log
    (tabela, registro_id, operacao, campos, rotulo, usuario_id, usuario_email)
  values (
    tg_table_name,
    coalesce((v_depois ->> 'id')::bigint, (v_antes ->> 'id')::bigint),
    v_operacao,
    v_campos,
    left(nullif(btrim(v_rotulo), ''), 120),
    auth.uid(),
    nullif(btrim(coalesce(auth.jwt() ->> 'email', '')), '')
  );

  return null;
exception
  when others then
    -- Auditoria nunca derruba a gravacao do painel. A falha aparece no log do
    -- Postgres (warnings) e a alteracao de conteudo segue normalmente.
    raise warning 'auditoria falhou em % (%): %', tg_table_name, v_operacao, sqlerrm;
    return null;
end;
$$;

revoke all on function public.registrar_auditoria() from public;

do $$
declare
  tabela text;
begin
  foreach tabela in array array[
    'acesso_rapido',
    'agenda_eventos',
    'arquivos',
    'avisos',
    'escala_ferias',
    'funcionarios',
    'info_juridico',
    'info_municipio',
    'info_orgaos',
    'manuais',
    'processos',
    'servicos',
    'sistemas',
    'veiculos'
  ] loop
    execute format('drop trigger if exists auditar_alteracoes on public.%I', tabela);
    execute format(
      'create trigger auditar_alteracoes after insert or update or delete on public.%I '
      'for each row execute function public.registrar_auditoria()',
      tabela
    );
  end loop;
end $$;

-- ----------------------------------------------------------------------------
-- Retencao (12 meses por padrao) — execucao manual pelo admin
--   select public.limpar_audit_log();      -- apaga o que passou de 12 meses
--   select public.limpar_audit_log(24);    -- ou outro prazo
-- ----------------------------------------------------------------------------
create or replace function public.limpar_audit_log(p_meses integer default 12)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_removidos bigint := 0;
begin
  if p_meses is null or p_meses < 1 then
    raise exception 'p_meses deve ser >= 1' using errcode = '22023';
  end if;

  if not public.is_admin() then
    raise exception 'Apenas admin pode limpar o historico' using errcode = '42501';
  end if;

  delete from public.audit_log
   where em < now() - make_interval(months => p_meses);

  get diagnostics v_removidos = row_count;
  return v_removidos;
end;
$$;

revoke all on function public.limpar_audit_log(integer) from public, anon;
grant execute on function public.limpar_audit_log(integer) to authenticated;
